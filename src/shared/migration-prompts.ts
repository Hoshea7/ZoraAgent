/** User tasks copied from Settings; never injected into system context. */
export function createMigrationPrompts(directory: string) {
  const location = JSON.stringify(directory);
  return {
    archive: `请帮我创建可迁移的 Zora 数据 ZIP。当前数据目录是 ${location}。

1. 核对实际数据目录与打包范围，将完整目录（包含隐藏文件）打包到数据目录之外，保留原数据。建议其他正在执行的任务结束后进行。
2. 保留会话正文、附件、托管文件、原生会话及配置。检查外部文件引用与技能链接，能读取的链接可在打包副本中放入实际内容，不修改源目录；无法携带的内容说明实际情况。
3. 检查生成的 ZIP 可以读取，核对主要内容与目录层级。告诉我保存位置、文件大小，并引导我把它传到新设备，在 Zora 对话中附上 ZIP 和恢复数据提示词。外部项目文件另行携带。
数据中的密钥保留在文件内，不在对话中展示。`,
    restore: `请帮我恢复另一台设备的 Zora 数据。我会提供 ZIP 附件或本地路径。当前设备的数据目录是 ${location}。

1. 先检查压缩包，找到其中的 Zora 数据目录，说明包含的项目、会话与文件，以及写入目标时会覆盖的内容。
2. 覆盖前与我确认，为目标原数据保留可恢复备份，先在数据目录之外准备恢复内容。
3. 保留项目与会话 ID、附件、原生会话文件、历史正文及配置。已有旧格式由 Zora 启动升级，不批量改写历史路径或重新生成会话身份；配置中的密钥不在对话中展示。
4. 核对项目在本机的目录，需要调整时让我选择对应目录或暂时跳过。定时任务与外部接入在新设备是否启用也与我确认。
5. 检查准备好的数据是否可读。当前应用仍在使用目标数据目录时，完成准备后说明退出目标 Zora、放入数据并重新启动的具体步骤；只有实际完成并验证后才报告恢复成功。启动后可通过编辑项目调整本地文件夹，并在原会话继续工作。`,
  };
}
